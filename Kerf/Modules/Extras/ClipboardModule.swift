import AppKit
import SwiftUI

/// The last 25 things copied, in memory only, and never what password managers mark as secret.
@Observable
final class ClipboardModule {
    static let shared = ClipboardModule()

    struct Clip: Identifiable, Equatable {
        enum Content: Equatable {
            case text(String)
            case image(NSImage)
            case files([URL])
        }

        let id = UUID()
        let content: Content
        let date: Date
    }

    private(set) var clips: [Clip] = []
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var ownChange = -1

    private static let secretTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        guard timer == nil else { return }
        changeCount = NSPasteboard.general.changeCount
        // Reading a number twice a second costs nothing; the pasteboard has no change notification.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardModule.shared.check() }
        }
        timer?.tolerance = 0.25
    }

    /// Switched off: nothing is read any more, and what was kept is forgotten.
    func stop() {
        timer?.invalidate()
        timer = nil
        clips = []
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard changeCount != ownChange else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return }
        let content: Clip.Content?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(text)
        } else if let image = NSImage(pasteboard: pasteboard) {
            content = .image(image)
        } else {
            content = nil
        }
        guard let content, clips.first?.content != content else { return }
        clips.insert(Clip(content: content, date: .now), at: 0)
        if clips.count > 25 { clips.removeLast(clips.count - 25) }
    }

    /// Puts a clip back on the pasteboard.
    func copy(_ clip: Clip) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch clip.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        case .image(let image): pasteboard.writeObjects([image])
        }
        ownChange = pasteboard.changeCount
        changeCount = pasteboard.changeCount
        Hub.shared.flash(.banner(.symbol("doc.on.clipboard.fill", .white), .symbol("checkmark", .white)), seconds: 1.4)
    }

    /// Lab only.
    func preview(_ texts: [String]) {
        clips = texts.map { Clip(content: .text($0), date: .now) }
    }
}
